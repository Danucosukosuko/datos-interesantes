ACC = {
    "acute": ["...#.", "..#..", "....."],
    "tilde": [".##.#", "#..#.", "....."],
    "diaer": [".#.#.", ".....", "....."],
}
ACCENTED = {"Á": ("A", "acute"), "É": ("E", "acute"), "Í": ("I", "acute"),
            "Ó": ("O", "acute"), "Ú": ("U", "acute"), "Ü": ("U", "diaer"),
            "Ñ": ("N", "tilde")}

HEIGHT = 10  # 3 filas de tilde + 7 de letra


def _mask(rows):
    return np.array([[c == "#" for c in r] for r in rows], dtype=bool)


_CACHE = {}


def glyph(ch):
    """Máscara booleana (10, w) del carácter."""
    ch = ch.upper()
    if ch in _CACHE:
        return _CACHE[ch]
    if ch in ACCENTED:
        base, acc = ACCENTED[ch]
        top = _mask(ACC[acc])
        if ch == "Í":  # la I tiene trazo fino: centramos la tilde
            top = _mask(["..#..", ".#...", "....."])
        m = np.vstack([top, _mask(G[base])])
    else:
        rows = G.get(ch, G["?"])
        w = len(rows[0])
        m = np.vstack([np.zeros((3, w), bool), _mask(rows)])
    _CACHE[ch] = m
    return m


def text_width(s, scale=1):
    if not s:
        return 0
    return (sum(glyph(c).shape[1] + 1 for c in s) - 1) * scale
